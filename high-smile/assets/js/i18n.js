  const CLAVE_ALMACEN = 'hs_idioma';
  const IDIOMAS = ['es', 'en'];
  const POR_DEFECTO = 'es';

  let idiomaActual = POR_DEFECTO;

  const traducir = (clave) => {
    const diccionario = TEXTOS[idiomaActual] || TEXTOS[POR_DEFECTO];
    return Object.prototype.hasOwnProperty.call(diccionario, clave) ? diccionario[clave] : clave;
  };

  const guardar = (idioma) => {
    try {
      window.localStorage.setItem(CLAVE_ALMACEN, idioma);
    } catch (error) {
      /* Navegación privada: la elección solo dura esta visita. */
    }
  };

  const preferenciaGuardada = () => {
    try {
      const valor = window.localStorage.getItem(CLAVE_ALMACEN);
      return IDIOMAS.indexOf(valor) >= 0 ? valor : '';
    } catch (error) {
      return '';
    }
  };

  const idiomaDelNavegador = () => {
    const idioma = (window.navigator.language || POR_DEFECTO).toLowerCase();
    return idioma.indexOf('en') === 0 ? 'en' : POR_DEFECTO;
  };

  const pintar = () => {
    document.documentElement.lang = idiomaActual;

    document.querySelectorAll('[data-i18n]').forEach((nodo) => {
      nodo.textContent = traducir(nodo.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((nodo) => {
      nodo.setAttribute('placeholder', traducir(nodo.dataset.i18nPh));
    });
    document.querySelectorAll('[data-i18n-content]').forEach((nodo) => {
      nodo.setAttribute('content', traducir(nodo.dataset.i18nContent));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((nodo) => {
      nodo.setAttribute('aria-label', traducir(nodo.dataset.i18nAria));
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((nodo) => {
      nodo.setAttribute('alt', traducir(nodo.dataset.i18nAlt));
    });

    document.querySelectorAll('[data-idioma]').forEach((boton) => {
      boton.setAttribute('aria-pressed', String(boton.dataset.idioma === idiomaActual));
    });
  };

  const aplicar = (idioma, recordar) => {
    idiomaActual = IDIOMAS.indexOf(idioma) >= 0 ? idioma : POR_DEFECTO;
    pintar();

    if (recordar) { guardar(idiomaActual); }
    document.dispatchEvent(new CustomEvent('hs:idioma', { detail: { idioma: idiomaActual } }));
  };

  const activarBotones = () => {
    document.addEventListener('click', (evento) => {
      const boton = evento.target.closest('[data-idioma]');
      if (boton) { aplicar(boton.dataset.idioma, true); }
    });
  };

  const iniciar = () => {
    aplicar(preferenciaGuardada() || idiomaDelNavegador(), false);
    activarBotones();
  };

  /* Disponible para el resto de scripts (formulario, mapa, etc.). */
  window.HighSmile = {
    t: traducir,
    idioma: () => idiomaActual,
    aplicar: aplicar
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', iniciar);
  } else {
    iniciar();
  }
